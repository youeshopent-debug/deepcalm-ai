"use client"

import { useEffect, useState } from "react"
import type { Locale } from "@/types"
import ActionableToolCards from "./ActionableToolCards"
import AiCounselor from "./AiCounselor"
import BreathingGuide from "./BreathingGuide"
import HealingToolbox from "./HealingToolbox"
import HeroSection from "./HeroSection"
import MeditationController from "./MeditationController"
import ResonanceWall from "./ResonanceWall"
import { Sparkles } from "lucide-react"

const MEDITATION_LABELS: Record<string, { title: string; desc: string; btn: string }> = {
  zh: { title: "🧘 AI 引导冥想", desc: "基于你的情绪状态，由 AI 动态生成专属冥想引导。呼吸、画面、声音三位一体，深度沉浸。", btn: "开始冥想" },
  en: { title: "🧘 AI-Guided Meditation", desc: "Dynamic meditation script generated by AI based on your emotional state. Breath, visuals, and sound — deeply immersive.", btn: "Start Meditation" },
}

export default function InteractiveAreas({
  lang,
  heroTitle,
  heroSubtitle,
  heroCtaText,
  children,
}: {
  lang: Locale
  heroTitle: string
  heroSubtitle: string
  heroCtaText: string
  children?: React.ReactNode
}) {
  const [showBreathing, setShowBreathing] = useState(false)
  const [showMeditation, setShowMeditation] = useState(false)
  const [initialPrompt, setInitialPrompt] = useState<string | undefined>(undefined)
  const labels = MEDITATION_LABELS[lang] || MEDITATION_LABELS.en

  /* ── 读取 URL query 中的 AI 上下文（?ai=...），注入 AiCounselor ── */
  useEffect(() => {
    try {
      const params = new URLSearchParams(window.location.search)
      const ai = params.get("ai")
      if (ai && ai.trim()) {
        setInitialPrompt(decodeURIComponent(ai))
      }
    } catch {
      /* 静默降级：无 query 时保持默认欢迎态 */
    }
  }, [])

  return (
    <>
      <HeroSection title={heroTitle} subtitle={heroSubtitle} ctaText={heroCtaText} />

      <section className="mx-auto max-w-6xl px-4 pt-2 sm:px-6">
        <h2 className="mb-3 inline-flex rounded-xl bg-[#132723] px-4 py-2 text-lg font-semibold text-[#f4faf6]">
          {lang === "zh" ? "睡眠与放松工具" : "Sleep and relaxation tools"}
        </h2>
        <ActionableToolCards
          locale={lang}
          onStartBreathing={() => setShowBreathing(true)}
        />
      </section>

      {/* AI-Guided Meditation Entry */}
      <section className="mx-auto max-w-6xl px-4 pb-5 sm:px-6">
        <div className="w-full">
          <div className="relative overflow-hidden rounded-2xl border border-[#c9d9d0] bg-[#f8fcf9] p-6 sm:p-8">
            {/* Decorative glow */}
            <div className="absolute -top-20 -right-20 w-40 h-40 rounded-full bg-[#c2f4df]/40 blur-3xl pointer-events-none" />
            <div className="absolute -bottom-10 -left-10 w-32 h-32 rounded-full bg-[#c2f4df]/40 blur-2xl pointer-events-none" />

            <div className="relative z-10 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
              <div className="flex-1">
                <h3 className="text-lg font-semibold text-[#172a24] mb-2">{labels.title}</h3>
                <p className="text-sm text-[#354c42] leading-relaxed max-w-md">{labels.desc}</p>
              </div>
              <button
                onClick={() => setShowMeditation(true)}
                className="flex-shrink-0 flex items-center gap-2 px-6 py-3 rounded-xl bg-[#e2f2e9] hover:bg-[#d4ebdf] border border-[#9ab8a8] text-[#214b3a] font-medium text-sm transition-all duration-200 hover:shadow-sm hover:shadow-dc-accent/10"
              >
                <Sparkles className="w-4 h-4" />
                {labels.btn}
              </button>
            </div>
          </div>
        </div>
      </section>

      {/* AI Counselor */}
      <section id="ai-counselor" className="mx-auto max-w-6xl scroll-mt-16 px-4 py-4 sm:px-6">
        <div className="w-full rounded-3xl border border-[#53746b] bg-[#132723] [--dc-text:#f4faf6] [--dc-muted:#d6e8df] [--dc-accent:#c2f4df] [--dc-deep:#132723] [--dc-surface:#203b33] [--dc-border:#789588]">
          <AiCounselor initialPrompt={initialPrompt} />
        </div>
      </section>

      <HealingToolbox />

      {children}

      {/* Resonance Wall */}
      <section id="resonance-wall" aria-labelledby="resonance-wall-title" className="mx-auto max-w-3xl px-4 py-8 sm:px-6 sm:py-10">
        <ResonanceWall />
      </section>

      {/* Breathing Guide Modal — triggered by ActionableToolCards */}
      {showBreathing && (
        <BreathingGuide onClose={() => setShowBreathing(false)} />
      )}

      {/* AI-Guided Meditation Modal */}
      {showMeditation && (
        <MeditationController onClose={() => setShowMeditation(false)} />
      )}
    </>
  )
}
